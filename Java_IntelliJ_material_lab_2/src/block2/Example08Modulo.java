package block2;

/*
 * PRZYKŁAD 7 — OPERATOR %
 *
 * % zwraca resztę z dzielenia całkowitego.
 * 10 % 3 = 1, 10 % 2 = 0, 11 % 2 = 1.
 *
 * OCZEKIWANY WYNIK:
 * 1
 * 0
 * 1
 */
public class Example08Modulo {
    public static void main(String[] args) {
        System.out.println(10 % 3);
        System.out.println(10 % 2);
        System.out.println(11 % 2);
    }
}
